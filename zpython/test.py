def generate_render_instruction_file(triangles, output_filename='render_instructions.json'):
    # Base render instruction template
    render_instructions = {
        "nbounces": 8,
        "rendermode": "phong",
        "camera": {
            "type": "pinhole",
            "width": 1600,
            "height": 1200,
            "position": [1.5, 2.0, -3.5],
            "lookAt": [0.0, 0.5, 0.0],
            "upVector": [0.0, 1.0, 0.0],
            "fov": 45.0,
            "exposure": 0.8
        },
        "scene": {
            "backgroundcolor": [0.25, 0.25, 0.25],
            "lightsources": [
                {
                    "type": "pointlight",
                    "position": [0, 1.0, 0],
                    "intensity": [0.75, 0.75, 0.75]
                }
            ],
            "shapes": []
        }
    }

    # Texture paths for variety
    textures = [
        "input-textures/brick.ppm",
        "input-textures/sphere.ppm", 
        "input-textures/fur.ppm",
        "input-textures/wood.ppm",  # Assuming this exists
        "input-textures/metal.ppm"  # Assuming this exists
    ]

    # Convert triangles to scene shapes
    for triangle in triangles:
        shape = {
            "type": "triangle",
            "v0": triangle[0],
            "v1": triangle[1],
            "v2": triangle[2],
            "material": {
                "ks": 0.1,
                "kd": 0.9,
                "specularexponent": 20,
                "diffusecolor": [0.8, 0.5, 0.5],
                "specularcolor": [1.0, 1.0, 1.0],
                "isreflective": False,
                "reflectivity": 1.0,
                "isrefractive": False,
                "refractiveindex": 1.0
            },
            "hastexture": False,
            "texturepath": random.choice(textures)
        }
        render_instructions["scene"]["shapes"].append(shape)

    # Write to JSON file
    with open(output_filename, 'w') as f:
        json.dump(render_instructions, f, indent=4)

    print(f"Render instruction file '{output_filename}' generated successfully.")

